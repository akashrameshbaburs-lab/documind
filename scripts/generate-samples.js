const MD_CONTENT = `# Field Notes: Observing Volcanoes

Volcanoes are openings in a planet's crust through which molten rock, ash and gases escape.
Most of them occur along the boundaries of tectonic plates, and the Ring of Fire around the
Pacific Ocean contains about 75 percent of the world's active volcanoes.

## Which country has the most volcanoes?

Indonesia has the largest number of active volcanoes of any country, with roughly 130 active
systems spread across its archipelago of more than 17,000 islands. The 1815 eruption of Mount
Tambora on Sumbawa, also in Indonesia, was the most powerful in recorded history and produced
the so-called year without a summer in 1816. Indonesia sits where the Indo-Australian Plate
subducts beneath the Eurasian Plate, which explains both the frequency of eruptions and the
extreme seismic activity of the region.

The United States ranks second if all volcanic systems are counted, largely because of Alaska
and the Cascade Range, while Japan and Chile also host more than one hundred each.

## How are volcanoes classified?

Geologists classify volcanoes by shape and eruption style:

- Shield volcanoes, such as Mauna Loa in Hawaii, are broad and gently sloping because their
  lava is fluid and travels far before solidifying.
- Stratovolcanoes, or composite cones, such as Mount Fuji in Japan and Mount Vesuvius in Italy,
  are steep and built from alternating layers of lava and ash. They erupt explosively.
- Calderas form when a magma chamber empties and the ground above it collapses, producing a
  large basin. Yellowstone in the United States is one of the best known examples.

## Measuring eruptions

The Volcanic Explosivity Index, abbreviated VEI, is a scale from 0 to 8 that describes the
magnitude of an eruption using the volume of ejected material, the height of the eruption
column and qualitative observations. Mount St. Helens in 1980 registered a VEI of 5, while
Tambora in 1815 reached a VEI of 7, the largest value recorded in modern history.

Lava temperature typically ranges from about 700 degrees Celsius for viscous rhyolitic magma
to about 1,200 degrees Celsius for fluid basaltic magma. Monitoring networks use seismometers,
tiltmeters and satellite instruments to detect the ground deformation and small earthquakes
that often precede an eruption.
`;

function buildPdf(filePath) {
  const doc = new PDFDocument({ size: "A4", margin: 56, info: { Title: "World Facts Handbook", Author: "DocuMind AI fixtures" } });
  const stream = fs.createWriteStream(filePath);
  doc.pipe(stream);

  PAGES.forEach(function (page, index) {
    if (index > 0) doc.addPage();
    doc.font("Helvetica-Bold").fontSize(16).text(page.title);
    doc.moveDown(0.6);
    page.paragraphs.forEach(function (p) {
      doc.font("Helvetica").fontSize(11).text(p, { align: "justify", lineGap: 3 });
      doc.moveDown(0.8);
    });
    doc.font("Helvetica-Oblique").fontSize(8).fillColor("#666666")
      .text("DocuMind AI evaluation fixture - page " + (index + 1), { align: "center" });
    doc.fillColor("#000000");
  });

  doc.end();
  return new Promise(function (resolve, reject) {
    stream.on("finish", resolve);
    stream.on("error", reject);
  });
}

async function main() {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  const pdfPath = path.join(OUT_DIR, "world-facts.pdf");
  await buildPdf(pdfPath);
  fs.writeFileSync(path.join(OUT_DIR, "field-notes.md"), MD_CONTENT, "utf-8");
  const sizeKb = (fs.statSync(pdfPath).size / 1024).toFixed(1);
  console.log("generated " + pdfPath + " (" + sizeKb + " KB, " + PAGES.length + " pages)");
  console.log("generated " + path.join(OUT_DIR, "field-notes.md"));
}

main().catch(function (err) {
  console.error("sample generation failed:", err);
  process.exit(1);
});
